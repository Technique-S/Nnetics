test.beforeEach(async({page})=>{page.on("dialog",dialog=>dialog.accept());});
const origin = process.env.NNETICS_BROWSER_BASE_URL || "http://127.0.0.1:3100";
async function start(page: Page, name = "Writer") {
    await page.goto("/demo/contractors");
    await page.getByRole("button", { name: "Start contractor demo" }).click();
    await page.getByLabel("Contractor name", { exact: true }).fill(name);
    await page.getByRole("button", { name: "Create contractor profile" }).click();
    await page.getByRole("button", { name: `Create private link · ${name}`, exact: true }).click();
    return await page.getByLabel("Private invitation link · shown once").inputValue();
}
async function requestWallet(page: Page, account: string) {
    await page.getByRole("button", { name: "Wallet details", exact: true }).click();
    await page.getByRole("textbox", { name: /testnet wallet/ }).fill(account);
    await page.getByRole("button", { name: "Prepare simulated verification", exact: true }).click();
    await page.getByRole("button", { name: "Simulate proof and request approval", exact: true }).click();
    await expect(page.getByText("Awaiting owner approval", { exact: true })).toBeVisible();
}
