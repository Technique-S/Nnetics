test("demo API isolates owners/contractors, blocks forged authority, CSRF and duplicate races", async ({ page, browser }) => {
    const link = await start(page), ctx = await browser.newContext({ baseURL: origin }), contractor = await ctx.newPage();
    await contractor.goto(link);
    await requestWallet(contractor, "writer-demo.testnet");
    await page.getByRole("button", { name: "Refresh owner records" }).click();
    await page.getByRole("button", { name: "Approve wallet · Writer", exact: true }).click();
    const owner = (await (await page.request.get("/api/demo/contractors/owner")).json());
    const profile = owner.profiles[0];
    const call = async (data: unknown) => page.request.post("/api/demo/contractors/owner", { headers: { Origin: origin }, data });
    await call({ action: "create-order", profileId: profile.id, reference: "RACE", title: "One article", amount: "1" });
    const records = await (await page.request.get("/api/demo/contractors/owner")).json(), order = records.orders[0];
    const invoice = { action: "submit-invoice", fields: { reference: "RACE-INV", orderId: order.id, amount: "1", asset: "NEAR", recipient: "" }, text: "Article delivered", description: "Article" };
    const results = await Promise.all([contractor.request.post("/api/demo/contractors/contractor", { headers: { Origin: origin }, data: invoice }), contractor.request.post("/api/demo/contractors/contractor", { headers: { Origin: origin }, data: { ...invoice, description:"Different submission", fields: { ...invoice.fields, reference: "RACE-OTHER" } } })]);
    expect(results.map(r => r.status()).sort()).toEqual([200, 400]);
    const retry = await contractor.request.post("/api/demo/contractors/contractor", {headers:{Origin:origin},data:invoice});
    expect(retry.status()).toBe(200);
    const retried=await retry.json();expect(retried.invoice.reference).toMatch(/^CTR-\d+-INV-0001$/);
    expect((await (await contractor.request.get("/api/demo/contractors/contractor")).json()).invoices).toHaveLength(1);
    const forged = await contractor.request.post("/api/demo/contractors/owner", { headers: { Origin: origin }, data: { action: "revoke-link", profileId: profile.id } });
    expect(forged.status()).toBe(400);
    const csrf = await page.request.post("/api/demo/contractors/owner", { headers: { Origin: "https://unrelated.example" }, data: { action: "revoke-link", profileId: profile.id } });
    expect(csrf.status()).toBe(400);
    const otherCtx = await browser.newContext({ baseURL: origin }), other = await otherCtx.newPage();
    await other.goto("/demo/contractors");
    await other.getByRole("button", { name: "Start contractor demo" }).click();
    const wrong = await other.request.post("/api/demo/contractors/owner", { headers: { Origin: origin }, data: { action: "issue-link", profileId: profile.id } });
    expect(wrong.status()).toBe(400);
    // Owner records survive refresh; invalid private-link switching clears the old capability.
    await page.reload();
    await expect(page.getByRole("heading", { name: "Writer", exact: true })).toBeVisible();
    await contractor.goto("/contractor?mode=demo#" + "0".repeat(64));
    await expect(contractor.getByRole("heading", { name: "Private access unavailable" })).toBeVisible();
    await contractor.reload();
    await expect(contractor.getByRole("heading", { name: "Private access unavailable" })).toBeVisible();
    await ctx.close();
    await otherCtx.close();
});
